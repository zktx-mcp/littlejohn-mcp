import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const sourcePath = resolve("src/stock-token-trade-history/stock-token-trade-history-registry.json");
const outputPath = resolve("src/stock-token-trade-history/stock-token-trade-history-registry.generated.ts");
const maximumSourceBytes = 4 * 1024 * 1024;

const source = await readFile(sourcePath);
if (source.length === 0 || source.length > maximumSourceBytes) {
  throw new TypeError("Stock Token trade-history registry size is invalid.");
}
const text = source.toString("utf8");
let value;
try { value = JSON.parse(text); }
catch { throw new TypeError("Stock Token trade-history registry JSON is invalid."); }
if (typeof value !== "object" || value === null || Array.isArray(value)) {
  throw new TypeError("Stock Token trade-history registry root is invalid.");
}
const canonicalSource = `${JSON.stringify(value, null, 2)}\n`;
if (text !== canonicalSource) {
  throw new TypeError("Stock Token trade-history registry source is not canonical formatted JSON.");
}
const sha256 = createHash("sha256").update(source).digest("hex");
const generated = [
  "// Generated by npm run generate:stock-token-trade-history-registry. Do not edit.",
  "",
  "// Source: src/stock-token-trade-history/stock-token-trade-history-registry.json",
  `export const stockTokenTradeHistoryRegistrySourceSha256 = ${JSON.stringify(sha256)} as const;`,
  `export const stockTokenTradeHistoryRegistryJson = ${JSON.stringify(text)} as const;`,
  "",
].join("\n");
await writeFile(outputPath, generated, "utf8");
