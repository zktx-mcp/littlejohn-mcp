const catalog = {
  contractVersion: "1",
  sources: [
    {
      uri: sourceRecords.sources[0].uri,
      observedAt: sourceRecords.sources[0].observedAt,
      rawResponseBytes: sourceRecords.sources[0].byteLength,
      rawResponseDigest: `0x${sourceRecords.sources[0].sha256}`,
    },
    {
      uri: sourceRecords.sources[1].uri,
      observedAt: sourceRecords.sources[1].observedAt,
      rawResponseBytes: sourceRecords.sources[1].byteLength,
      rawResponseDigest: `0x${sourceRecords.sources[1].sha256}`,
    },
  ],
  dispositionSetDigest: hash32(canonicalBytes(dispositions)),
  dispositions,
};
const rendered = generatedHeader + generatedPrefix + JSON.stringify(catalog, null, 2) +
  generatedSuffix;

try {
  await writeFile(candidate, rendered, { encoding: "utf8", flag: "wx" });
  const written = await readFile(candidate, "utf8");
  if (
    written !== rendered ||
    !written.startsWith(generatedHeader + generatedPrefix) ||
    !written.endsWith(generatedSuffix)
  ) {
    throw new TypeError("Generated catalog bytes changed after write.");
  }
  const payload = written.slice(
    (generatedHeader + generatedPrefix).length,
    -generatedSuffix.length,
  );
  const reparsed = JSON.parse(payload);
  if (
    !canonicalBytes(reparsed).equals(canonicalBytes(catalog)) ||
    reparsed.dispositionSetDigest !== hash32(canonicalBytes(reparsed.dispositions)) ||
    reparsed.dispositions.length !== assets.length
  ) {
    throw new TypeError("Generated catalog candidate failed re-admission.");
  }
  await rename(candidate, target);
} catch (error) {
  await unlink(candidate).catch(() => undefined);
  throw error;
}

