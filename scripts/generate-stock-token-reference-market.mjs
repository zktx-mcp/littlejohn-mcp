const admitAssets = (input) => {
  exactKeys(input, ["assets"], "Robinhood asset root");
  if (!Array.isArray(input.assets) || input.assets.length === 0 ||
      input.assets.length > maximumSourceMembers) {
    throw new TypeError("Robinhood asset members are outside the admitted bound.");
  }
  const seenUids = new Set();
  const seenDeployments = new Set();
  return input.assets.map((raw, index) => {
    exactKeys(raw, assetMemberKeys, `Robinhood asset ${index}`);
    assertBoundedJson(raw, `Robinhood asset ${index}`);
    const uid = assetUid(raw.id);
    if (seenUids.has(uid)) throw new TypeError("Robinhood asset UIDs are duplicated.");
    seenUids.add(uid);
    const symbol = safeText(
      raw.tokenSymbol,
      32,
      /^[A-Z0-9][A-Z0-9.-]*$/u,
      `Robinhood asset ${index} symbol`,
    );
    const name = safeText(raw.tokenName, 512, undefined, `Robinhood asset ${index} name`);
    const sourceStatus = safeText(raw.status, 64, /^[A-Z][A-Z0-9_]*$/u,
      `Robinhood asset ${index} status`);
    if (!Array.isArray(raw.deployments) || raw.deployments.length > 8) {
      throw new TypeError(`Robinhood asset ${index} deployments are invalid.`);
    }
    const deployments = raw.deployments.map((deployment, deploymentIndex) => {
      exactKeys(deployment, ["chainId", "contractAddress", "networkName"],
        `Robinhood asset ${index} deployment ${deploymentIndex}`);
      const contractAddress = evmAddress(
        deployment.contractAddress,
        `Robinhood asset ${index} deployment ${deploymentIndex}`,
      );
      if (seenDeployments.has(contractAddress)) {
        throw new TypeError("Robinhood deployment addresses are duplicated.");
      }
      seenDeployments.add(contractAddress);
      return {
        chainId: positiveSafeInteger(deployment.chainId, "Deployment chain ID"),
        contractAddress,
        networkName: safeText(deployment.networkName, 128, undefined, "Deployment network name"),
      };
    });
    return { assetUid: uid, sourceStatus, symbol, name, deployments };
  });
};

const admitFeeds = (input) => {
  if (!Array.isArray(input) || input.length === 0 || input.length > maximumSourceMembers) {
    throw new TypeError("Chainlink feed members are outside the admitted bound.");
  }
  const seenProxies = new Set();
  const seenCandidateIdentities = new Set();
  return input.map((raw, sourceRow) => {
    allowedKeys(raw, feedMemberKeys, requiredFeedMemberKeys, `Chainlink feed ${sourceRow}`);
    allowedKeys(raw.docs, feedDocKeys, [], `Chainlink feed ${sourceRow} docs`);
    assertBoundedJson(raw, `Chainlink feed ${sourceRow}`);
    const proxyAddress = evmAddress(raw.proxyAddress, `Chainlink feed ${sourceRow} proxy`);
    evmAddress(raw.contractAddress, `Chainlink feed ${sourceRow} contract`);
    if (raw.secondaryProxyAddress !== undefined) {
      evmAddress(raw.secondaryProxyAddress, `Chainlink feed ${sourceRow} secondary proxy`);
    }
    if (seenProxies.has(proxyAddress)) throw new TypeError("Chainlink proxies are duplicated.");
    seenProxies.add(proxyAddress);
    const name = safeText(raw.name, 512, undefined, `Chainlink feed ${sourceRow} name`);
    positiveSafeInteger(raw.contractVersion, `Chainlink feed ${sourceRow} contract version`);
    positiveSafeInteger(raw.decimals, `Chainlink feed ${sourceRow} decimals`);
    positiveSafeInteger(raw.heartbeat, `Chainlink feed ${sourceRow} heartbeat`);
    if (typeof raw.multiply !== "string" || !/^[1-9][0-9]*$/u.test(raw.multiply)) {
      throw new TypeError(`Chainlink feed ${sourceRow} multiplier is invalid.`);
    }
    if (typeof raw.threshold !== "number" || !Number.isFinite(raw.threshold)) {
      throw new TypeError(`Chainlink feed ${sourceRow} threshold is invalid.`);
    }
    for (const key of [
      "baseAsset", "quoteAsset", "baseAssetEntityId", "quoteAssetEntityId",
      "marketHours", "assetClass", "productType", "productSubType",
      "deliveryChannelCode",
    ]) {
      if (Object.hasOwn(raw.docs, key) && typeof raw.docs[key] !== "string") {
        throw new TypeError(`Chainlink feed ${sourceRow} docs.${key} is invalid.`);
      }
    }
    const baseAsset = raw.docs.baseAsset;
    const quoteAsset = raw.docs.quoteAsset;
    if (name.startsWith("Robinhood ") && typeof baseAsset === "string") {
      const identity = `${name}\0${baseAsset}\0${String(quoteAsset)}`;
      if (seenCandidateIdentities.has(identity)) {
        throw new TypeError("Chainlink candidate identities are duplicated.");
      }
      seenCandidateIdentities.add(identity);
    }
    return { ...raw, name, proxyAddress, sourceRow };
  });
};

const consistentFeed = (asset, feed) =>
  feed.name === `Robinhood ${asset.symbol} / USD` &&
  feed.docs?.baseAssetEntityId === `crypto-${asset.symbol}` &&
  (feed.docs?.quoteAssetEntityId === undefined || feed.docs.quoteAssetEntityId === "forex-USD") &&
  feed.docs?.marketHours === "us_equities_24/5" &&
  feed.docs?.assetClass === "Equity" &&
  feed.docs?.productType === "Price" &&
  feed.docs?.productSubType === "calculatedPrice" &&
  feed.docs?.deliveryChannelCode === "DF" &&
  feed.contractVersion === 6 &&
  feed.decimals === 8 &&
  feed.heartbeat === 86_400 &&
  feed.multiply === "100000000" &&
  feed.threshold === 0.5;

const createDispositions = (assets, feeds) => {
  const symbols = new Map();
  for (const asset of assets) {
    const values = symbols.get(asset.symbol) ?? [];
    values.push(asset);
    symbols.set(asset.symbol, values);
  }
  const dispositions = assets.map((asset) => {
    const chainDeployments = asset.deployments.filter((entry) => entry.chainId === 4663);
    const unmapped = (reason) => ({ asset, mapping: { status: "unmapped", reason } });
    if (asset.sourceStatus !== "ASSET_STATUS_ACTIVE") return unmapped("asset_inactive");
    if (chainDeployments.length === 0) return unmapped("asset_deployment_missing");
    if (chainDeployments.length !== 1) return unmapped("asset_deployment_ambiguous");
    if ((symbols.get(asset.symbol) ?? []).length !== 1) {
      return unmapped("asset_symbol_ambiguous");
    }
    const candidates = feeds.filter((feed) =>
      feed.name.startsWith("Robinhood ") && feed.docs?.baseAsset === asset.symbol);
    if (candidates.length === 0) return unmapped("feed_not_found");
    if (candidates.length !== 1) return unmapped("feed_ambiguous");
    const feed = candidates[0];
    if (feed.docs?.quoteAsset !== "USD" || !feed.name.endsWith(" / USD")) {
      return unmapped("feed_non_usd");
    }
    if (!consistentFeed(asset, feed)) return unmapped("feed_source_inconsistent");
    return {
      asset,
      mapping: {
        status: "mapped",
        selectedDeployment: chainDeployments[0],
        feed: {
          feedId: feed.proxyAddress,
          proxyAddress: feed.proxyAddress,
          expectedDescription: feed.name,
          decimals: 8,
          heartbeatSeconds: 86_400,
          availability: "session_dependent_24_5",
          sourceRow: feed.sourceRow,
        },
      },
    };
  }).sort((left, right) =>
    left.asset.assetUid < right.asset.assetUid
      ? -1
      : left.asset.assetUid > right.asset.assetUid
        ? 1
        : 0);
  return dispositions;
};

